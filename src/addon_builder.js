const fs = require('fs');
const path = require('path');
const AdmZip = require('adm-zip');
const crypto = require('crypto');

function uuidv4() {
  return crypto.randomUUID();
}

function buildBlockBehaviorJson(identifier, geoIdentifier) {
  const shortId = identifier.split(':').pop();
  return JSON.stringify({
    "format_version": "1.20.80",
    "minecraft:block": {
      "description": {
        "identifier": identifier,
        "menu_category": {
          "category": "construction"
        },
        "traits": {
          "minecraft:placement_direction": {
            "enabled_states": ["minecraft:cardinal_direction"]
          }
        }
      },
      "permutations": [
        { "condition": "q.block_state('minecraft:cardinal_direction') == 'north'", "components": { "minecraft:transformation": { "rotation": [0, 0, 0] } } },
        { "condition": "q.block_state('minecraft:cardinal_direction') == 'west'", "components": { "minecraft:transformation": { "rotation": [0, 90, 0] } } },
        { "condition": "q.block_state('minecraft:cardinal_direction') == 'south'", "components": { "minecraft:transformation": { "rotation": [0, 180, 0] } } },
        { "condition": "q.block_state('minecraft:cardinal_direction') == 'east'", "components": { "minecraft:transformation": { "rotation": [0, -90, 0] } } }
      ],
      "components": {
        "minecraft:geometry": geoIdentifier,
        "minecraft:collision_box": false,
        "minecraft:material_instances": {
          "*": {
            "texture": shortId,
            "render_method": "alpha_test"
          }
        },
        "minecraft:destructible_by_mining": {
          "seconds_to_destroy": 0.1
        }
      }
    }
  }, null, 2);
}

function buildTerrainTextureJson(shortId) {
  return JSON.stringify({
    "num_mip_levels": 4,
    "padding": 8,
    "resource_pack_name": "ModelPack",
    "texture_name": "atlas.terrain",
    "texture_data": {
      [shortId]: {
        "textures": `textures/blocks/${shortId}`
      }
    }
  }, null, 2);
}

function buildManifest(type, name, desc) {
  return JSON.stringify({
    "format_version": 2,
    "header": {
      "name": name,
      "description": desc,
      "uuid": uuidv4(),
      "version": [1, 0, 0],
      "min_engine_version": [1, 20, 80]
    },
    "modules": [
      {
        "type": type,
        "uuid": uuidv4(),
        "version": [1, 0, 0]
      }
    ]
  }, null, 2);
}

function buildEntityBehaviorJson(identifier, customComponents) {
  const defaultComponents = {
    "minecraft:physics": {},
    "minecraft:pushable": { "is_pushable": true, "is_pushable_by_piston": true }
  };
  return JSON.stringify({
    "format_version": "1.20.80",
    "minecraft:entity": {
      "description": {
        "identifier": identifier,
        "is_spawnable": true,
        "is_summonable": true,
        "is_experimental": false
      },
      "components": { ...defaultComponents, ...(customComponents || {}) }
    }
  }, null, 2);
}

function buildClientEntityJson(identifier, geoIdentifier, shortId) {
  return JSON.stringify({
    "format_version": "1.10.0",
    "minecraft:client_entity": {
      "description": {
        "identifier": identifier,
        "materials": { "default": "entity_alphatest" },
        "textures": { "default": `textures/entity/${shortId}` },
        "geometry": { "default": geoIdentifier },
        "render_controllers": [ "controller.render.default" ],
        "spawn_egg": {
          "base_color": "#ff0000",
          "overlay_color": "#00ff00"
        }
      }
    }
  }, null, 2);
}

function buildTerrainTextureJsonMulti(blockIds) {
  const textureData = {};
  blockIds.forEach(shortId => {
    textureData[shortId] = {
      "textures": `textures/blocks/${shortId}`
    };
  });
  return JSON.stringify({
    "num_mip_levels": 4,
    "padding": 8,
    "resource_pack_name": "ModelPack",
    "texture_name": "atlas.terrain",
    "texture_data": textureData
  }, null, 2);
}

function packageAddon(options) {
  const { addonName, items, outputDir } = options;
  const zip = new AdmZip();
  const bpFolder = `${addonName}_BP/`;
  const rpFolder = `${addonName}_RP/`;

  zip.addFile(bpFolder + "manifest.json", Buffer.from(buildManifest("data", `${addonName} BP`, "Behavior Pack generated by AI")));
  zip.addFile(rpFolder + "manifest.json", Buffer.from(buildManifest("resources", `${addonName} RP`, "Resource Pack generated by AI")));

  const blockIds = [];
  let hasTexture = false;
  let firstTexturePath = null;

  items.forEach(item => {
    const shortId = item.assetName || item.asset_name;
    const fullId = `custom:${shortId}`;
    const geoIdentifier = `geometry.${shortId}`;
    const geoPath = path.join(outputDir, `${shortId}.geo.json`);
    const texturePath = path.join(outputDir, `${shortId}.png`);
    const textureExists = fs.existsSync(texturePath);

    if (textureExists) {
      hasTexture = true;
      if (!firstTexturePath) firstTexturePath = texturePath;
    }

    if (item.mode === "block") {
      blockIds.push(shortId);
      zip.addFile(bpFolder + `blocks/${shortId}.json`, Buffer.from(buildBlockBehaviorJson(fullId, geoIdentifier)));
      if (fs.existsSync(geoPath)) zip.addLocalFile(geoPath, rpFolder + "models/blocks/");
      if (textureExists) zip.addLocalFile(texturePath, rpFolder + "textures/blocks/", `${shortId}.png`);
    } else {
      zip.addFile(bpFolder + `entities/${shortId}.json`, Buffer.from(buildEntityBehaviorJson(fullId, item.components)));
      zip.addFile(rpFolder + `entity/${shortId}.entity.json`, Buffer.from(buildClientEntityJson(fullId, geoIdentifier, shortId)));
      if (fs.existsSync(geoPath)) zip.addLocalFile(geoPath, rpFolder + "models/entity/");
      if (textureExists) zip.addLocalFile(texturePath, rpFolder + "textures/entity/", `${shortId}.png`);
    }
  });

  if (blockIds.length > 0) {
    zip.addFile(rpFolder + `textures/terrain_texture.json`, Buffer.from(buildTerrainTextureJsonMulti(blockIds)));
  }

  if (hasTexture && firstTexturePath) {
    zip.addLocalFile(firstTexturePath, bpFolder, "pack_icon.png");
    zip.addLocalFile(firstTexturePath, rpFolder, "pack_icon.png");
  } else {
    zip.addFile(bpFolder + "pack_icon.png", Buffer.from(""));
    zip.addFile(rpFolder + "pack_icon.png", Buffer.from(""));
  }

  const addonPath = path.join(outputDir, `${addonName}.mcaddon`);
  zip.writeZip(addonPath);
  return addonPath;
}

function createAddon(options) {
  return packageAddon({
    addonName: options.assetName,
    items: [{ assetName: options.assetName, mode: options.mode }],
    outputDir: options.outputDir
  });
}

module.exports = { createAddon, packageAddon };
