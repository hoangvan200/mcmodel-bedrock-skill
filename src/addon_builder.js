const fs = require('fs');
const path = require('path');
const AdmZip = require('adm-zip');
const crypto = require('crypto');

function uuidv4() {
  return crypto.randomUUID();
}

function buildBlockBehaviorJson(identifier, geoIdentifier) {
  const shortId = identifier.split(':').pop();
  return JSON.stringify({
    "format_version": "1.20.80",
    "minecraft:block": {
      "description": {
        "identifier": identifier,
        "menu_category": {
          "category": "construction"
        },
        "traits": {
          "minecraft:placement_direction": {
            "enabled_states": ["minecraft:cardinal_direction"]
          }
        }
      },
      "permutations": [
        { "condition": "q.block_state('minecraft:cardinal_direction') == 'north'", "components": { "minecraft:transformation": { "rotation": [0, 0, 0] } } },
        { "condition": "q.block_state('minecraft:cardinal_direction') == 'west'", "components": { "minecraft:transformation": { "rotation": [0, 90, 0] } } },
        { "condition": "q.block_state('minecraft:cardinal_direction') == 'south'", "components": { "minecraft:transformation": { "rotation": [0, 180, 0] } } },
        { "condition": "q.block_state('minecraft:cardinal_direction') == 'east'", "components": { "minecraft:transformation": { "rotation": [0, -90, 0] } } }
      ],
      "components": {
        "minecraft:geometry": geoIdentifier,
        "minecraft:collision_box": false,
        "minecraft:material_instances": {
          "*": {
            "texture": shortId,
            "render_method": "alpha_test"
          }
        },
        "minecraft:destructible_by_mining": {
          "seconds_to_destroy": 0.1
        }
      }
    }
  }, null, 2);
}

function buildTerrainTextureJson(shortId) {
  return JSON.stringify({
    "num_mip_levels": 4,
    "padding": 8,
    "resource_pack_name": "ModelPack",
    "texture_name": "atlas.terrain",
    "texture_data": {
      [shortId]: {
        "textures": `textures/blocks/${shortId}`
      }
    }
  }, null, 2);
}

function buildManifest(type, name, desc) {
  return JSON.stringify({
    "format_version": 2,
    "header": {
      "name": name,
      "description": desc,
      "uuid": uuidv4(),
      "version": [1, 0, 0],
      "min_engine_version": [1, 20, 80]
    },
    "modules": [
      {
        "type": type,
        "uuid": uuidv4(),
        "version": [1, 0, 0]
      }
    ]
  }, null, 2);
}

function buildEntityBehaviorJson(identifier) {
  return JSON.stringify({
    "format_version": "1.20.80",
    "minecraft:entity": {
      "description": {
        "identifier": identifier,
        "is_spawnable": true,
        "is_summonable": true,
        "is_experimental": false
      },
      "components": {
        "minecraft:physics": {},
        "minecraft:pushable": { "is_pushable": true, "is_pushable_by_piston": true }
      }
    }
  }, null, 2);
}

function buildClientEntityJson(identifier, geoIdentifier, shortId) {
  return JSON.stringify({
    "format_version": "1.10.0",
    "minecraft:client_entity": {
      "description": {
        "identifier": identifier,
        "materials": { "default": "entity_alphatest" },
        "textures": { "default": `textures/entity/${shortId}` },
        "geometry": { "default": geoIdentifier },
        "render_controllers": [ "controller.render.default" ],
        "spawn_egg": {
          "base_color": "#ff0000",
          "overlay_color": "#00ff00"
        }
      }
    }
  }, null, 2);
}

function createAddon(options) {
  const { assetName, identifier, mode, geoPath, texturePath, outputDir } = options;
  const shortId = assetName;
  const fullId = `custom:${shortId}`;

  const zip = new AdmZip();

  const bpFolder = `${shortId}_BP/`;
  zip.addFile(bpFolder + "manifest.json", Buffer.from(buildManifest("data", `${shortId} BP`, "Behavior Pack generated by AI")));
  
  const rpFolder = `${shortId}_RP/`;
  zip.addFile(rpFolder + "manifest.json", Buffer.from(buildManifest("resources", `${shortId} RP`, "Resource Pack generated by AI")));

  if (mode === "block") {
    zip.addFile(bpFolder + `blocks/${shortId}.json`, Buffer.from(buildBlockBehaviorJson(fullId, identifier)));
    zip.addFile(rpFolder + `textures/terrain_texture.json`, Buffer.from(buildTerrainTextureJson(shortId)));
    
    zip.addLocalFile(geoPath, rpFolder + "models/blocks/");
    if (texturePath) {
      zip.addLocalFile(texturePath, rpFolder + "textures/blocks/", `${shortId}.png`);
    }
  } else {
    zip.addFile(bpFolder + `entities/${shortId}.json`, Buffer.from(buildEntityBehaviorJson(fullId)));
    zip.addFile(rpFolder + `entity/${shortId}.entity.json`, Buffer.from(buildClientEntityJson(fullId, identifier, shortId)));
    
    zip.addLocalFile(geoPath, rpFolder + "models/entity/");
    if (texturePath) {
      zip.addLocalFile(texturePath, rpFolder + "textures/entity/", `${shortId}.png`);
    }
  }

  if (texturePath) {
    zip.addLocalFile(texturePath, bpFolder, "pack_icon.png");
    zip.addLocalFile(texturePath, rpFolder, "pack_icon.png");
  }

  const addonPath = path.join(outputDir, `${shortId}.mcaddon`);
  zip.writeZip(addonPath);
  return addonPath;
}

module.exports = { createAddon };
